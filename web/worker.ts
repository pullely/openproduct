// The worker's entry (openproduct-performance OPP13).
//
// `wrangler.jsonc` used to point `main` straight at the file OpenNext
// generates. It now points here, and this file does two things with it:
//
//   1. re-exports it unchanged — every request still goes through OpenNext's
//      own `fetch`, and the Durable Object classes it exports stay exported
//      (none is bound today; the names are kept so binding one later is a
//      config change and not a code change);
//
//   2. registers that `fetch` where `src/opennext/in-process-queue.ts` can
//      find it, so a stale ISR document can be re-rendered in the background
//      by the same worker that served it — with no `WORKER_SELF_REFERENCE`
//      binding, which this component cannot express per environment (D8).
//
// Outside `src/` on purpose: it imports a generated file that exists only
// after `opennextjs-cloudflare build`, so it is neither type-checked by
// `tsc --noEmit` nor linted by `eslint src`. Wrangler bundles it with esbuild
// at deploy (and at `--dry-run`, which is what the verify profile runs).

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler.
import openNext from "./.open-next/worker.js";

import { registerSelfFetch } from "./src/opennext/in-process-queue";

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler.
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

type Fetch = (request: Request, env: unknown, ctx: { waitUntil(p: Promise<unknown>): void }) => Promise<Response>;

const fetchImpl: Fetch = (request, env, ctx) => (openNext as { fetch: Fetch }).fetch(request, env, ctx);

registerSelfFetch(fetchImpl);

export default {
  fetch: fetchImpl,
};
